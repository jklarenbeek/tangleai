/**
 * Order 15: the scorer at parity with the published one.
 *
 * The fixtures were produced by RUNNING `task_eval/evaluation.py`
 * (`benchmark/scripts/locomo-parity-fixtures.py`, mode `oracle`), and
 * every row must be reproduced at the precision it records — ten
 * decimals for an F1, exact strings for a normalization or a stem. The
 * committed fixtures are Tangle-authored text plus the release's
 * vocabulary as a word list; the dataset-derived rows redistribute
 * LoCoMo text and live in gitignored `test-output/`, checked only when
 * present. The edge cases the order names are pinned on their own
 * below, without any fixture: an empty prediction, an integer answer,
 * a category-3 truth carrying `;`, a multi-hop answer with commas.
 */

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';

import { INIT_COMMAND, dialogIdsOf, loadLocomo, sessionsOf } from '../../benchmark/lib/locomo.ts';
import { porterStem } from '../../benchmark/lib/porter.ts';
import {
  CATEGORY_5_REASON,
  adversarialKeywordScore,
  f1Score,
  multiHopF1,
  normalizeAnswer,
  numpyMean,
  officialScore,
  pySplit,
  pyStrip,
  type LocomoCategory,
} from '../../benchmark/lib/locomo-parity.ts';

interface Fixture {
  generated: Record<string, string>;
  normalize: Array<{ input: string, expected: string }>;
  stems: Array<[string, string]>;
  rows: Array<{ id: string, category: LocomoCategory, prediction: string, answer: string | number, expected: number }>;
  adversarial: Array<{ output: string, expected: 0 | 1 }>;
}

const fixture = JSON.parse(await readFile('test/fixtures/locomo-parity.json', 'utf8')) as Fixture;
const vocabulary = JSON.parse(await readFile('test/fixtures/locomo-parity-vocabulary.json', 'utf8')) as { tokens: number, stems: Array<[string, string]> };
const DATASET_ROWS = 'test-output/locomo-parity-dataset.json';

/** Ten decimals — what the fixture records. */
const PRECISION = 5e-11;

describe('the parity fixtures are an oracle, not a reading', () => {
  it('were generated by running the official evaluator', () => {
    assert.equal(fixture.generated.mode, 'oracle');
    assert.equal(fixture.generated.evaluator, 'benchmark/locomo/task_eval/evaluation.py');
    assert.match(fixture.generated.stemmer, /NLTK_EXTENSIONS/);
    assert.ok(fixture.rows.length >= 40 && fixture.stems.length >= 100);
  });
});

describe('normalizeAnswer — the official order, including the mistake', () => {
  for (const { input, expected } of fixture.normalize) {
    it(`${JSON.stringify(input)} → ${JSON.stringify(expected)}`, () => {
      assert.equal(normalizeAnswer(input), expected);
    });
  }

  it('removes punctuation before articles, so the-cat keeps its article', () => {
    assert.equal(normalizeAnswer('the-cat'), 'thecat');
    assert.equal(normalizeAnswer('the cat'), 'cat');
  });

  it('splits and strips on Python whitespace, not JavaScript\'s', () => {
    assert.deepEqual(pySplit('a\x1cb\x85c　d'), ['a', 'b', 'c', 'd']);
    assert.deepEqual(pySplit('﻿a'), ['﻿a'], 'a BOM is not whitespace to Python');
    assert.equal(pyStrip('\x1f x \x85'), 'x');
  });
});

describe('porterStem — NLTK\'s variant', () => {
  it('reproduces every stem the fixture recorded', () => {
    const wrong = fixture.stems.filter(([word, stem]) => porterStem(word) !== stem)
      .map(([word, stem]) => `${word}: got ${porterStem(word)}, nltk ${stem}`);
    assert.deepEqual(wrong, []);
  });

  it(`reproduces the release's whole question-and-answer vocabulary (${vocabulary.tokens} tokens)`, () => {
    assert.equal(vocabulary.stems.length, vocabulary.tokens);
    const wrong = vocabulary.stems.filter(([word, stem]) => porterStem(word) !== stem)
      .map(([word, stem]) => `${word}: got ${porterStem(word)}, nltk ${stem}`);
    assert.deepEqual(wrong, []);
  });

  it('is the NLTK variant, not the paper', () => {
    assert.equal(porterStem('dying'), 'die', 'the irregular table');
    assert.equal(porterStem('dies'), 'die', 'ies -> ie on four letters');
    assert.equal(porterStem('flies'), 'fli');
    assert.equal(porterStem('enjoy'), 'enjoy', 'y -> i needs a consonant before it');
    assert.equal(porterStem('happy'), 'happi');
    assert.equal(porterStem('geology'), 'geolog', 'logi measured with its l');
  });
});

describe('f1Score and multiHopF1 — every oracle row, at ten decimals', () => {
  for (const row of fixture.rows) {
    it(`[${row.category}] ${row.id}`, () => {
      const outcome = officialScore({ category: row.category, prediction: row.prediction, answer: row.answer });
      assert.equal(outcome.scored, true);
      if (outcome.scored) {
        assert.ok(Math.abs(outcome.f1 - row.expected) <= PRECISION,
          `got ${outcome.f1}, the official evaluator says ${row.expected}`);
      }
    });
  }
});

describe('the order\'s own edge cases', () => {
  it('an empty prediction scores 0, never NaN', () => {
    assert.equal(f1Score('', 'anything'), 0);
    assert.equal(multiHopF1('', 'a, b'), 0);
    assert.equal(f1Score('', ''), 0);
  });

  it('an integer answer is coerced with String()', () => {
    const outcome = officialScore({ category: 2, prediction: '2022', answer: 2022 });
    assert.deepEqual(outcome, { scored: true, category: 2, f1: 1, groundTruth: '2022' });
  });

  it('a category-3 ground truth is cut at the first semicolon', () => {
    const outcome = officialScore({ category: 3, prediction: 'counseling', answer: 'Psychology; counseling' });
    assert.equal(outcome.scored && outcome.groundTruth, 'Psychology');
    assert.equal(outcome.scored && outcome.f1, 0);
    const other = officialScore({ category: 4, prediction: 'counseling', answer: 'Psychology; counseling' });
    assert.ok(other.scored && other.f1 > 0, 'only category 3 truncates');
  });

  it('a multi-hop answer with commas is split before normalization', () => {
    assert.equal(multiHopF1('yellow, red', 'red, yellow'), 1);
    assert.equal(multiHopF1('red', 'red, yellow'), 0.5);
    assert.equal(f1Score('yellow, red', 'red, yellow'), 1, 'and the single-hop scorer just drops the commas');
    // `a` is an article: it normalizes to nothing on both sides and can never match
    assert.equal(multiHopF1('b, a', 'a, b'), 0.5);
  });

  it('category 5 is excluded with its reason, and the official keyword rule is documented', () => {
    assert.deepEqual(officialScore({ category: 5, prediction: 'Paris', answer: 'x' }),
      { scored: false, category: 5, reason: CATEGORY_5_REASON });
    for (const { output, expected } of fixture.adversarial) assert.equal(adversarialKeywordScore(output), expected, output);
  });

  it('sums like NumPy, so long multi-hop answers agree to the bit', () => {
    const values = Array.from({ length: 19 }, (_, i) => 1 / (i + 3));
    const naive = values.reduce((a, b) => a + b, 0) / values.length;
    const pairwise = numpyMean(values);
    assert.ok(Math.abs(naive - pairwise) < 1e-15);
    assert.equal(numpyMean([0.5]), 0.5);
    assert.equal(numpyMean([1, 0, 0, 1]), 0.5);
  });
});

