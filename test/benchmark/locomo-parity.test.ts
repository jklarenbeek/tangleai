// the release, when present
// ---------------------------------------------------------------------------

const dataset = await loadLocomo();
if (!dataset.available) {
  // eslint-disable-next-line no-console
  console.log(`# locomo parity dataset tests skipped — submodule absent. ${INIT_COMMAND}`);
}

describe('the scorer over the pinned release', { skip: !dataset.available }, () => {
  it('scores every scorable answer against itself as 1, except the eleven category-3 truths cut at a semicolon', () => {
    const samples = dataset.available ? dataset.samples : [];
    let scored = 0;
    let integers = 0;
    const semicolons: string[] = [];
    const deviations: string[] = [];
    for (const sample of samples) {
      for (const qa of sample.qa) {
        if (qa.category === 5 || qa.answer === undefined) continue;
        if (typeof qa.answer === 'number') integers++;
        const outcome = officialScore({ category: qa.category, prediction: String(qa.answer), answer: qa.answer });
        assert.equal(outcome.scored, true);
        if (!outcome.scored) continue;
        scored++;
        assert.ok(pySplit(normalizeAnswer(outcome.groundTruth)).length > 0, `${sample.sample_id}: ${JSON.stringify(qa.answer)} normalizes to nothing`);
        if (qa.category === 3 && String(qa.answer).includes(';')) {
          // the TRUTH is cut at the `;`, the prediction is not — the official asymmetry, reproduced
          assert.ok(outcome.f1 < 1, `${sample.sample_id}: ${JSON.stringify(qa.answer)} should not match its own truncation`);
          semicolons.push(sample.sample_id);
          continue;
        }
        if (outcome.f1 !== 1) deviations.push(`${sample.sample_id} [${qa.category}] ${JSON.stringify(qa.answer)} → ${outcome.f1}`);
      }
    }
    assert.equal(scored, 1540);
    assert.equal(integers, 6, 'the six integer answers coerce and score');
    assert.equal(semicolons.length, 11);
    assert.deepEqual(deviations, []);
  });

  it('reproduces the dataset-derived oracle rows when they were generated locally', { skip: !existsSync(DATASET_ROWS) }, async () => {
    const local = JSON.parse(await readFile(DATASET_ROWS, 'utf8')) as {
      turnVocabulary: Array<[string, string]>,
      rows: Array<{ id: string, category: LocomoCategory, prediction: string, answer: string | number, expected: number }>,
    };
    const wrongStems = local.turnVocabulary.filter(([word, stem]) => porterStem(word) !== stem).map(([w, s]) => `${w}: got ${porterStem(w)}, nltk ${s}`);
    assert.deepEqual(wrongStems, []);
    const wrongRows: string[] = [];
    for (const row of local.rows) {
      const outcome = officialScore({ category: row.category, prediction: row.prediction, answer: row.answer });
      if (!outcome.scored || Math.abs(outcome.f1 - row.expected) > PRECISION) {
        wrongRows.push(`${row.id}: got ${outcome.scored ? outcome.f1 : 'excluded'}, official ${row.expected}`);
      }
    }
    assert.deepEqual(wrongRows, [], `${wrongRows.length} of ${local.rows.length} rows disagree`);
    assert.ok(local.rows.length > 4000);
  });

  it('every evidence turn text stems without throwing', () => {
    const samples = dataset.available ? dataset.samples : [];
    for (const sample of samples) {
      const ids = dialogIdsOf(sample);
      assert.ok(ids.size > 0);
      for (const session of sessionsOf(sample)) {
        for (const turn of session.turns) pySplit(normalizeAnswer(turn.text)).forEach(porterStem);
      }
    }
  });
});
