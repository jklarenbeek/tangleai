const plural = new Intl.PluralRules('fr');
const number = new Intl.NumberFormat('fr-FR');
/** A number in the language's digits; anything but a number reads 0, so a closure never prints NaN. */
const num = (value: unknown) => number.format(typeof value === 'number' ? value : 0);
/** A count in French digits with the noun form it takes (French counts 0 and 1 as singular). */
const count = (value: unknown, one: string, other: string) => `${num(value)} ${plural.select(typeof value === 'number' ? value : 0) === 'one' ? one : other}`;
const onOff = (on: boolean) => on ? 'activée' : 'désactivée';
/** A length in hours as French writes it on a clock: 1 h, 1 h 30, 2 h. */
const hours = (value: unknown) => {
  const length = typeof value === 'number' ? value : 0;
  const whole = Math.floor(length);
  const minutes = Math.round((length - whole) * 60);
  return `${number.format(whole)} h${minutes ? ` ${String(minutes).padStart(2, '0')}` : ''}`;
};

