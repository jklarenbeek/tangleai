export type CategoryKey = '1' | '2' | '3' | '4';

export interface ByCategory {
  overall: number;
  /** `null` when the run holds no question of that category. */
  byCategory: Record<CategoryKey, number | null>;
}

/** Per-question values grouped by category; `overall` is the mean over categories 1–4 together. */
class Means {
  private readonly values = new Map<number, number[]>();
  private readonly mean: (values: readonly number[]) => number;

  constructor(mean: (values: readonly number[]) => number) { this.mean = mean; }

  add(category: number, value: number): void {
    const list = this.values.get(category) ?? [];
    list.push(value);
    this.values.set(category, list);
  }

  get size(): number {
    return SCORABLE_CATEGORIES.reduce((n, c) => n + (this.values.get(c)?.length ?? 0), 0);
  }

  summary(): ByCategory {
    const all = SCORABLE_CATEGORIES.flatMap((c) => this.values.get(c) ?? []);
    const byCategory = {} as Record<CategoryKey, number | null>;
    for (const c of SCORABLE_CATEGORIES) {
      const list = this.values.get(c) ?? [];
      byCategory[String(c) as CategoryKey] = list.length === 0 ? null : this.mean(list);
    }
    return { overall: all.length === 0 ? 0 : this.mean(all), byCategory };
  }
}

/** The official aggregate: NumPy's mean over per-question F1. */
const f1Means = (): Means => new Means(numpyMean);
/** Evidence recall averages as the recall instrument averages. */
const recallMeans = (): Means => new Means(average);

/** The official F1 of one prediction; `null` for category 5. */
function f1Of(question: QaQuestion, prediction: string): number | null {
  if (question.category === 5 || question.answer === undefined) return null;
  const scored = officialScore({ category: question.category, prediction, answer: question.answer });
  return scored.scored ? scored.f1 : null;
}

/** The released answer as the scorer would have a model say it (category 3 cut at its first `;`). */
export function oraclePrediction(question: QaQuestion): string | null {
  if (question.answer === undefined || question.category === 5) return null;
  const text = String(question.answer);
  return question.category === 3 ? pyStrip(text.split(';')[0]) : text;
}

