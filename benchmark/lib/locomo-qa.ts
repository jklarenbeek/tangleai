/** Split citations into those the prompt listed and those it did not. */
export function checkCitations(citations: readonly string[], listed: ReadonlySet<string>): { resolved: string[], unresolved: string[] } {
  const resolved: string[] = [];
  const unresolved: string[] = [];
  for (const id of new Set(citations)) (listed.has(id) ? resolved : unresolved).push(id);
  return { resolved, unresolved };
}

