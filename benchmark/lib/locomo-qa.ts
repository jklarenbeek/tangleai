const DIA_ID = /\bD\d+:\d+\b/g;

/**
 * A program answers from a slot, not a schema: the slot may hold a
 * phrase, a JSON list of what the sub-calls returned, or a reduce's
 * result. Read it in the rival's favour — every string and number leaf,
 * joined — and take the turn ids it names as its citations. A map
 * result's bookkeeping members (`slot`, `error`) are not answer text.
 */
export function horizonAnswer(text: string): { answer: string, citations: string[] } {
  let value: unknown = text;
  try { value = JSON.parse(text); } catch { /* prose is an answer too */ }
  const leaves: string[] = [];
  const walk = (v: unknown): void => {
    if (typeof v === 'string') { if (v.trim() !== '') leaves.push(v.trim()); return; }
    if (typeof v === 'number') { leaves.push(String(v)); return; }
    if (Array.isArray(v)) { for (const item of v) walk(item); return; }
    if (v !== null && typeof v === 'object') {
      for (const [key, item] of Object.entries(v as Record<string, unknown>)) if (key !== 'slot' && key !== 'error') walk(item);
    }
  };
  walk(value);
  const joined = leaves.join(', ');
  const citations = [...new Set([...joined.matchAll(DIA_ID)].map((m) => m[0]))];
  const answer = joined.replace(/\[?\bD\d+:\d+\b\]?/g, '').replace(/\s+/g, ' ').replace(/\s+,/g, ',').replace(/^[\s,]+|[\s,]+$/g, '').trim();
  return { answer, citations };
}

