export interface QaQuestion extends GoldQuestion {
  /** `<sample_id>#<index in qa>` — stable across runs and tiers. */
  id: string;
  sampleId: string;
  index: number;
  category: 1 | 2 | 3 | 4 | 5;
  text: string;
  /** As released; absent on 444 adversarial questions. */
  answer?: string | number;
  adversarialAnswer?: string;
}

export function questionsOf(sample: LocomoSample, corpus: ConversationCorpus): QaQuestion[] {
  return sample.qa.map((qa, index): QaQuestion => {
    const gold = (qa.evidence ?? []).map((id) => addressOf(sample.sample_id, id));
    return {
      id: `${sample.sample_id}#${index}`,
      sampleId: sample.sample_id,
      index,
      category: qa.category,
      text: qa.question,
      ...(qa.answer === undefined ? {} : { answer: qa.answer }),
      ...(qa.adversarial_answer === undefined ? {} : { adversarialAnswer: qa.adversarial_answer }),
      gold,
      resolvable: gold.filter((address) => corpus.addresses.has(address)).length,
      universe: corpus.turns.length,
    };
  });
}

export interface SampleSpec {
  seed: number;
  perCategory: number;
  adversarial: number;
}

/**
 * A seeded, stratified draw: `perCategory` questions from each scorable
 * category and `adversarial` from category 5, in release order. The
 * same spec over the same release draws the same ids, which is what
 * lets the keyless report list the sample the live tier answers.
 */
export function sampleQuestions(questions: readonly QaQuestion[], spec: SampleSpec): QaQuestion[] {
  const random = mulberry32(spec.seed);
  const chosen = new Set<string>();
  for (const category of [1, 2, 3, 4, 5] as const) {
    const pool = questions.filter((q) => q.category === category);
    const n = category === 5 ? spec.adversarial : spec.perCategory;
    for (const i of drawDistinct(random, pool.length, Math.min(n, pool.length))) chosen.add(pool[i].id);
  }
  return questions.filter((q) => chosen.has(q.id));
}

