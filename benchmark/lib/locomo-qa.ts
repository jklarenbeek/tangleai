const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** `8 May 2023` — the form the release writes its temporal answers in, read as UTC like every instant here. */
export function dateText(at: string): string {
  const d = new Date(at);
  return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

/** The speaker a memory's tags name, if any (a crystallized survivor keeps its own first). */
function speakerOf(unit: MemoryUnit): string | null {
  return unit.tags.find((tag) => !tag.startsWith('session:')) ?? null;
}

/** One memory as the prompt lists it: `[id] (date) speaker: text`. */
export function contextLine(unit: MemoryUnit): string {
  const speaker = speakerOf(unit);
  return `[${unit.id}] (${dateText(unit.at)}) ${speaker === null ? '' : `${speaker}: `}${unit.text}`;
}

