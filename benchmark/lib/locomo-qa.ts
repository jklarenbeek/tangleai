class BudgetStop extends Error {
  constructor(reason: string) { super(reason); this.name = 'BudgetStop'; }
}

function emptyCost(): Cost {
  return { turns: 0, tokens: 0, promptTokens: 0, completionTokens: 0, ms: 0, replayed: 0 };
}

/** The run's one account and everything charged to it. */
interface Account {
  account: ReturnType<typeof createBudgetAccount>;
  timer: () => number;
}

/** A settled call, charged to every tally it belongs to; a replay is counted as a call AND as a replay. */
function charge(tallies: readonly Cost[], latencies: number[], usage: any, elapsed: number, replayed: boolean): void {
  const prompt = typeof usage?.prompt_tokens === 'number' ? usage.prompt_tokens : 0;
  const completion = typeof usage?.completion_tokens === 'number' ? usage.completion_tokens : 0;
  const total = typeof usage?.total_tokens === 'number' && usage.total_tokens > 0 ? usage.total_tokens : prompt + completion;
  for (const cost of tallies) {
    cost.turns++;
    cost.tokens += total;
    cost.promptTokens += prompt;
    cost.completionTokens += completion;
    cost.ms += elapsed;
    if (replayed) cost.replayed++;
  }
  latencies.push(elapsed);
}

/** The purchase-time latency JarenJS attaches to a replay, or null for a wire reply. */
function replayMs(result: unknown): number | null {
  if (typeof result !== 'object' || result === null) return null;
  const replayed = (result as { replayed?: unknown }).replayed;
  if (typeof replayed !== 'object' || replayed === null) return null;
  const ms = (replayed as { ms?: unknown }).ms;
  return typeof ms === 'number' && Number.isFinite(ms) ? ms : null;
}

/**
 * A chat client whose non-replayed logical calls are charged to the account
 * and whose every result is charged to the report tallies. The up-front plan
 * bounds all possible misses before concurrency starts; after the reply, the
 * upstream replay marker distinguishes remembered work without a host-owned
 * key preflight.
 */
function meter(client: ChatClient, shared: Account, tallies: readonly Cost[], latencies: number[]): { endpoint: { provider: string }, complete: (request: any) => Promise<any> } {
  return {
    endpoint: client.endpoint,
    async complete(request: any) {
      const stop = shared.account.stop();
      if (stop !== null) throw new BudgetStop(stop);
      const started = shared.timer();
      const result = await client.complete(request);
      const rememberedMs = replayMs(result);
      const replayed = rememberedMs !== null;
      const elapsed = rememberedMs ?? shared.timer() - started;
      if (!replayed) {
        shared.account.reserve();
        shared.account.settle(result.usage);
      }
      charge(tallies, latencies, result.usage, elapsed, replayed);
      return result;
    },
  };
}

/**
 * The long-horizon agent's client: metered like every other, and two
 * things more. Every SUB-CALL request — the only requests that carry
 * corpus text — is handed to `onSubcall`, which is how the row's
 * ceiling is read (was a gold turn in any request a model received);
 * and every call carries a deadline, because an authoring call on a
 * thinking model has been measured to hang past five minutes upstream.
 * Sub-calls are extraction-shaped and run with thinking off under a run
 * whose control is off; the authoring call keeps the client's default
 * unless asked otherwise.
 */
function horizonClient(
  client: ChatClient,
  shared: Account,
  tallies: readonly Cost[],
  latencies: number[],
  hooks: { onSubcall: (text: string) => void, onFailure: (message: string) => void, timeoutMs: number, authorThinkingOff: boolean, subcallThinkingOff: boolean },
): { endpoint: { provider: string }, complete: (request: any) => Promise<any> } {
  return {
    endpoint: client.endpoint,
    async complete(request: any) {
      const isAuthor = request.responseFormat !== undefined;
      if (!isAuthor) hooks.onSubcall(transcriptText(request.messages ?? []));
      const thinkingOff = isAuthor ? hooks.authorThinkingOff : hooks.subcallThinkingOff;
      const deadline = hooks.timeoutMs > 0 ? AbortSignal.timeout(hooks.timeoutMs) : undefined;
      const signal = request.signal === undefined ? deadline : deadline === undefined ? request.signal : AbortSignal.any([request.signal, deadline]);
      const sent = {
        ...request,
        ...(signal === undefined ? {} : { signal }),
        ...(thinkingOff ? { reasoning: { effort: 'none' } } : {}),
      };
      const stop = shared.account.stop();
      if (stop !== null) throw new BudgetStop(stop);
      const started = shared.timer();
      let result: any;
      try {
        result = await client.complete(sent);
      } catch (error) {
        // the runner turns a failed sub-call into a recorded `{ error }` and moves on — right for the
        // program, but the run's error census must still say what the wire answered
        hooks.onFailure(`${isAuthor ? 'authoring' : 'sub-call'}: ${error instanceof Error ? error.message : String(error)}`);
        throw error;
      }
      const rememberedMs = replayMs(result);
      const replayed = rememberedMs !== null;
      const elapsed = rememberedMs ?? shared.timer() - started;
      if (!replayed) {
        shared.account.reserve();
        shared.account.settle(result.usage);
      }
      charge(tallies, latencies, result.usage, elapsed, replayed);
      return result;
    },
  };
}

/**
 * What the wire cache already holds of a run's texts, and what it does
 * not — read BEFORE the plan, so the plan counts only the requests the
 * wire will actually be asked for. Without a cache (or under `fresh`)
 * everything is missing.
 */
async function partitionEmbeddings(
  cache: WireCache | undefined,
  fresh: boolean,
  endpoint: ReplayEndpoint,
  texts: readonly string[],
): Promise<{ known: Map<string, Float32Array>, missing: string[] }> {
  const unique = [...new Set(texts)];
  const known = new Map<string, Float32Array>();
  if (cache === undefined || fresh) return { known, missing: unique };
  const vectors = await cache.embeddingHits(endpoint, unique);
  const missing: string[] = [];
  unique.forEach((text, i) => {
    const vector = vectors[i];
    if (vector === undefined) missing.push(text); else known.set(text, vector);
  });
  return { known, missing };
}

/**
 * Every text a run's ranked rows will embed that the cache did not
 * hold, embedded up front in batches of `EMBED_BATCH` — so the
 * pipeline's per-session embed calls hit a table instead of the wire,
 * and the request count is known before the first request is made.
 * What the wire answers is remembered. The pipeline itself runs
 * unchanged: the seam answers the same vectors under the same
 * identity, only the batching differs.
 */
async function preEmbed(
  wire: Embedder,
  missing: readonly string[],
  known: Map<string, Float32Array>,
  shared: Account,
  tally: { requests: number, texts: number, cached: number },
): Promise<Map<string, Float32Array>> {
  const table = new Map<string, Float32Array>(known);
  tally.cached += known.size;
  for (let i = 0; i < missing.length; i += EMBED_BATCH) {
    const batch = missing.slice(i, i + EMBED_BATCH);
    const stop = shared.account.stop();
    if (stop !== null) throw new BudgetStop(stop);
    shared.account.reserve();
    const vectors = await wire.embed(batch);
    tally.requests++;
    tally.texts += batch.length;
    batch.forEach((text, j) => table.set(text, vectors[j]));
  }
  return table;
}

/** The embedder the pipeline sees: the table first, the wire for a miss. */
function tableEmbedder(wire: Embedder, table: Map<string, Float32Array>, dims: number): Embedder & { dims: number } {
  return {
    model: wire.model,
    dims,
    async embed(texts, hooks) {
      const missing = texts.filter((t) => !table.has(t));
      if (missing.length > 0) {
        const vectors = await wire.embed(missing, hooks);
        missing.forEach((t, i) => table.set(t, vectors[i]));
      }
      return texts.map((t) => table.get(t)!);
    },
  };
}

/** The number of `/embeddings` requests `preEmbed` will make over these texts — the same dedup, so the plan is exact. */
function embedRequestsFor(texts: readonly string[]): number {
  return Math.ceil(new Set(texts).size / EMBED_BATCH);
}

/** The texts of a corpus, in ingest order. */
function textsOf(corpus: IngestCorpus): string[] {
  const texts: string[] = [];
  for (const session of corpus.sessions) for (const input of session.inputs) texts.push(input.text);
  return texts;
}

function emptyAdversarial(): LiveConfiguration['adversarial'] {
  return { planned: 0, judged: 0, correct: 0, accuracy: null, keyword: 0, unanswered: { wire: 0, budget: 0 }, judgeFailed: 0, cost: emptyCost() };
}

export async function runLocomoQaLive(dataset: Dataset, options: LiveRunOptions): Promise<LiveReport> {
  const { env } = options;
  const k = options.k ?? DEFAULT_K;
  const spec: SampleSpec = {
    seed: options.seed ?? DEFAULT_SEED,
    perCategory: options.perCategory ?? DEFAULT_PER_CATEGORY,
    adversarial: options.adversarial ?? DEFAULT_ADVERSARIAL,
  };
  const clock = options.clock ?? ((): Date => new Date());
  const timer = options.timer ?? ((): number => performance.now());
  const progress = options.onProgress ?? ((): void => {});
  const { samples, restricted } = samplesOf(dataset, options.samples);
  const wire = options.embedder;
  const isWire = env.embedModel !== '';
  const rows = options.rowSpecs ?? rowsOf(options.rows ?? DEFAULT_LIVE_ROWS);
  const horizon: HorizonOptions = { ...HORIZON_DEFAULTS, ...options.horizon };

  // --- the corpus, the questions, the sample: exactly as the keyless tier draws them
  const all: QaQuestion[] = [];
  const perConversation = new Map<string, Conversation>();
  for (const sample of samples) {
    const entry = conversationOf(sample);
    all.push(...entry.questions);
    perConversation.set(sample.sample_id, entry);
  }
  const sampled = sampleQuestions(all, spec);
  const sample = sampleBlock(spec, sampled);
  const scorable = sampled.filter((q) => q.category !== 5);
  const adversarial = sampled.filter((q) => q.category === 5);
  const horizonQuestions = rows.some((row) => row.kind === 'long-horizon') ? horizonSubset(scorable, horizon.perCategory, spec.seed) : [];

  // --- the plan, checked against the ceiling before a single request
  const texts: string[] = [];
  const corpora = new Set(rows.map((row) => row.corpus).filter((c): c is RowCorpus => c !== undefined));
  for (const entry of perConversation.values()) {
    if (corpora.has('turns')) texts.push(...textsOf(entry.corpus));
    if (corpora.has('observation')) texts.push(...textsOf(entry.observations));
    if (corpora.has('summary')) texts.push(...textsOf(entry.summaries));
  }
  if (corpora.size > 0) texts.push(...sampled.map((q) => q.text));
  const fresh = options.fresh === true;
  const resolvedEmbed = resolveEndpoint({
    provider: env.provider,
    baseUrl: env.baseUrl ?? undefined,
    model: wire.model,
  });
  const replayEndpoint: ReplayEndpoint = {
    provider: resolvedEmbed.provider,
    base: resolvedEmbed.base,
    model: wire.model,
  };
  const partition = isWire && texts.length > 0
    ? await partitionEmbeddings(options.cache, fresh, replayEndpoint, texts)
    : { known: new Map<string, Float32Array>(), missing: [] as string[] };
  const embedRequests = isWire ? embedRequestsFor(partition.missing) : 0;
  let chatCalls = 0;
  let judgeCalls = 0;
  for (const row of rows) {
    if (row.kind === 'long-horizon') chatCalls += horizonQuestions.length * horizon.turnsPerQuestion;
    else { chatCalls += scorable.length; judgeCalls += adversarial.length * 2; }
  }
  const planned = embedRequests + chatCalls + judgeCalls;
  const skipped = planned > env.maxCalls
    ? `${planned} planned requests for ${rows.map((row) => row.key).join(', ')} (${embedRequests} embedding, ${chatCalls} answers, ${judgeCalls} adversarial answers and judgments) exceed TANGLE_AI_MAX_CALLS=${env.maxCalls}; nothing was spent — answer fewer rows per run, lower --questions/--adversarial/--horizon-questions, or raise the ceiling`
    : null;

  const dims0 = wire.dims;
  const generated = {
    at: clock().toISOString(),
    provider: env.provider,
    model: env.model,
    judgeModel: env.modelStrong,
    embedder: { model: wire.model, dims: dims0 ?? 0 },
    keySource: env.keySource,
    thinking: options.thinking ?? 'default' as const,
  };
  const header = {
    benchmark: 'locomo' as const,
    instrument: 'locomo-qa-live' as const,
    generated,
    dataset: {
      path: LOCOMO_DATASET, sha256: dataset.sha256, bytes: dataset.bytes, schemaValid: dataset.valid,
      conversations: samples.length, restricted,
    },
    config: {
      embedder: { model: wire.model, dims: dims0 ?? 0 },
      k,
      ingest: 'per-session' as const,
      clock: 'the last session instant of each conversation',
      maxPairs: DEFAULT_MAX_PAIRS,
    },
    sample,
  };
  const run: LiveRun = {
    at: generated.at,
    rows: rows.map((row) => row.key),
    plan: { embedRequests, chatCalls, judgeCalls, planned, maxCalls: env.maxCalls, skipped },
    embedding: { requests: 0, texts: 0, cached: 0 },
    spent: { turns: 0, tokens: 0, ms: 0 },
    replayed: 0,
    errors: { count: 0, sample: [] },
  };
  if (skipped !== null) return { ...header, configIdentities: { identities: [], rows: [] }, runs: [run], configurations: [] };
  if (options.configIdentityFor === undefined) {
    throw new Error('a live run resolves its config identity before it may spend; hand runLocomoQaLive a configIdentityFor');
  }

  const shared: Account = { account: createBudgetAccount({ turns: env.maxCalls }, timer), timer };
  const errors: string[] = [];
  let errorCount = 0;
  const noteError = (message: string): void => { errorCount++; if (errors.length < 10) errors.push(excerpt(message, 160)); };

  // --- the corpora embedded once, through the wire, under the ceiling — the cache answering what it can
  const embedding = { requests: 0, texts: 0, cached: 0 };
  const table = isWire && texts.length > 0 ? await preEmbed(wire, partition.missing, partition.known, shared, embedding) : new Map<string, Float32Array>();
  const dims = wire.dims ?? table.values().next().value?.length ?? 0;
  const embedder = isWire ? tableEmbedder(wire, table, dims) : wire;
  const identity = { model: embedder.model, dims };
  if (dims > 0) {
    header.generated.embedder = identity;
    header.config.embedder = identity;
  }
  if (embedding.requests + embedding.cached > 0) progress(`embedded ${embedding.texts} texts in ${embedding.requests} requests, ${embedding.cached} from the cache (${identity.model}, ${dims} dims)`);

  // --- the rows
  const configurations: LiveConfiguration[] = [];
  for (const row of rows) {
    if (row.kind === 'long-horizon') {
      configurations.push(await runHorizonRow(row, {
        env, horizon, questions: horizonQuestions, perConversation, samples, shared, timer, noteError, progress,
        client: options.horizonClient ?? options.chat,
        thinking: generated.thinking,
      }));
      continue;
    }

    const ingest = emptyCensus();
    let unranked = 0;
    const f1 = f1Means();
    const ceiling = recallMeans();
    const citedRecall = recallMeans();
    const citations = { cited: 0, uncited: 0, total: 0, unresolved: 0, answersWithUnresolved: 0 };
    const unanswered = { wire: 0, budget: 0 };
    let invalid = 0;
    const cost = emptyCost();
    const latencies: number[] = [];
    const results: QuestionResult[] = [];

    const adversarialCost = emptyCost();
    const adversarialLatencies: number[] = [];
    const adversarialAnswerer = createStructuredOutput({ client: meter(options.chat, shared, [adversarialCost], adversarialLatencies), schema: ANSWER_SCHEMA, name: 'locomo_answer' });
    const judge = createStructuredOutput({ client: meter(options.judge, shared, [adversarialCost], adversarialLatencies), schema: JUDGE_SCHEMA, name: 'locomo_judge' });
    const lane = { judged: 0, correct: 0, keyword: 0, judgeFailed: 0, unanswered: { wire: 0, budget: 0 } };

    for (const s of samples) {
      const entry = perConversation.get(s.sample_id)!;
      const { corpus } = entry;
      const own = entry.questions.filter((q) => sample.ids.includes(q.id));
      if (own.length === 0) continue;
      const turnById = new Map(corpus.turns.map((t) => [t.address, t]));
      let skippedSeen = false;
      // what this batch adds, so the line after concurrency settles reports
      // what was ANSWERED rather than what was planned — a wire failure or a
      // budget stop returns early, and a progress line that counted the plan
      // would report answers nobody bought
      const before = {
        answered: f1.size, wire: unanswered.wire, budget: unanswered.budget, invalid,
        judged: lane.judged, laneWire: lane.unanswered.wire, laneBudget: lane.unanswered.budget, judgeFailed: lane.judgeFailed,
      };

      // what this row hands the prompt for one question
      let contextOf: (i: number) => { context: MemoryUnit[], retrieved: Set<string> };
      let units: MemoryUnit[] = [];
      if (row.kind === 'long-context') {
        const whole = wholeConversation(entry);
        units = whole.context;
        contextOf = () => whole;
      } else {
        units = (await ingestConversation(corpusFor(row, entry), { embedder, thresholds: row.thresholds!, census: ingest })).units;
        const vectors = await embedder.embed(own.map((q) => q.text));
        contextOf = (i) => {
          const { context, retrieved, skipped } = retrieve(units, vectors[i], row.retrieval?.k ?? k, identity, s.sample_id, row.retrieval?.minScore ?? 0);
          if (!skippedSeen) { unranked += skipped; skippedSeen = true; }
          return { context, retrieved };
        };
      }

      await mapConcurrent(own, env.maxConcurrency, async (q, i) => {
        const { context, retrieved } = contextOf(i);
        const listed = new Set(context.map((u) => u.id));

        if (q.category !== 5) {
          const mine = emptyCost();
          const answerer = createStructuredOutput({ client: meter(options.chat, shared, [cost, mine], latencies), schema: ANSWER_SCHEMA, name: 'locomo_answer' });
          let reply: { value: AnswerValue } | { errors: unknown[], raw: string };
          try {
            reply = await answerer.generate(answerMessages(q.text, context)) as typeof reply;
          } catch (error) {
            if (error instanceof BudgetStop) unanswered.budget++;
            else { unanswered.wire++; noteError(`${q.id}: ${error instanceof Error ? error.message : String(error)}`); }
            return;
          }
          let answer: string;
          let cited: string[] = [];
          let bad = false;
          if ('value' in reply) {
            answer = reply.value.answer;
            cited = reply.value.citations;
          } else {
            invalid++;
            bad = true;
            answer = reply.raw;
          }
          const check = checkCitations(cited, listed);
          citations.total += cited.length;
          citations.unresolved += check.unresolved.length;
          if (check.unresolved.length > 0) citations.answersWithUnresolved++;
          if (check.resolved.length > 0) citations.cited++; else citations.uncited++;
          const citedAddresses = new Set<string>();
          for (const unit of context) if (check.resolved.includes(unit.id)) for (const a of addressesOf(unit.evidence, s.sample_id)) citedAddresses.add(a);
          const own1 = f1Of(q, answer)!;
          const ceil = evidenceRecall(q.gold, retrieved);
          const citedR = evidenceRecall(q.gold, citedAddresses);
          f1.add(q.category, own1);
          ceiling.add(q.category, ceil);
          citedRecall.add(q.category, citedR);
          results.push({
            id: q.id, category: q.category as 1 | 2 | 3 | 4, f1: own1, ceiling: ceil, citedRecall: citedR,
            cited: check.resolved.length > 0, unresolved: check.unresolved.length, invalid: bad, tokens: mine.tokens, ms: mine.ms, replayed: mine.replayed,
            ...(options.digestPrompt === undefined ? {} : { promptSha256: await options.digestPrompt(context.map(contextLine)) }),
          });
          return;
        }

        // category 5: answer, then judge
        let answerText: string;
        try {
          const reply = await adversarialAnswerer.generate(answerMessages(q.text, context)) as { value: AnswerValue } | { raw: string };
          answerText = 'value' in reply ? reply.value.answer : reply.raw;
        } catch (error) {
          if (error instanceof BudgetStop) lane.unanswered.budget++;
          else { lane.unanswered.wire++; noteError(`${q.id}: ${error instanceof Error ? error.message : String(error)}`); }
          return;
        }
        lane.keyword += adversarialKeywordScore(answerText);
        const evidence = q.gold.map((address) => turnById.get(address)).filter((t) => t !== undefined)
          .map((t) => {
            const unit = units.find((u) => addressesOf(u.evidence, s.sample_id)[0] === t.address);
            return `(${dateText(new Date(t.at).toISOString())}) ${t.speaker}: ${unit?.text ?? '(turn text not in the store)'}`;
          });
        try {
          const verdict = await judge.generate(judgeMessages({
            question: q.text,
            trap: q.adversarialAnswer ?? '',
            ...(q.answer === undefined ? {} : { released: String(q.answer) }),
            evidence,
            answer: answerText,
          })) as { value: JudgeValue } | { errors: unknown[] };
          if ('value' in verdict) { lane.judged++; if (verdict.value.correct) lane.correct++; } else lane.judgeFailed++;
        } catch (error) {
          if (error instanceof BudgetStop) lane.unanswered.budget++;
          else { lane.judgeFailed++; noteError(`${q.id} judge: ${error instanceof Error ? error.message : String(error)}`); }
        }
      });
      const plannedHere = own.filter((q) => q.category !== 5).length;
      const adversarialHere = own.length - plannedHere;
      progress(`${row.key} ${s.sample_id}: planned ${plannedHere}`
        + ` / answered ${f1.size - before.answered}`
        + ` / wire ${unanswered.wire - before.wire}`
        + ` / budget ${unanswered.budget - before.budget}`
        + ` / invalid ${invalid - before.invalid}`
        + (adversarialHere === 0 ? '' : ` · adversarial planned ${adversarialHere}`
          + ` / judged ${lane.judged - before.judged}`
          + ` / wire ${lane.unanswered.wire - before.laneWire}`
          + ` / budget ${lane.unanswered.budget - before.laneBudget}`
          + ` / judge failed ${lane.judgeFailed - before.judgeFailed}`));
    }

    results.sort((a, b) => sample.ids.indexOf(a.id) - sample.ids.indexOf(b.id));
    configurations.push({
      key: row.key,
      label: row.label,
      kind: row.kind,
      ...(row.corpus === undefined ? {} : { corpus: row.corpus }),
      run: 0,
      ...(row.thresholds === undefined ? {} : { thresholds: row.thresholds, ingest, retrieval: { unranked } }),
      questions: { planned: scorable.length, answered: f1.size, unanswered, invalid, results },
      f1: f1.summary(),
      ceiling: ceiling.summary(),
      citedRecall: citedRecall.summary(),
      citations,
      cost,
      latency: latencyOf(latencies),
      adversarial: {
        planned: adversarial.length,
        judged: lane.judged,
        correct: lane.correct,
        accuracy: lane.judged === 0 ? null : lane.correct / lane.judged,
        keyword: lane.keyword,
        unanswered: lane.unanswered,
        judgeFailed: lane.judgeFailed,
        cost: adversarialCost,
      },
    });
  }

  const spent = shared.account.spent();
  run.embedding = embedding;
  run.spent = { turns: spent.turns, tokens: spent.tokens, ms: spent.ms };
  run.replayed = configurations.reduce((n, c) => n + c.cost.replayed + c.adversarial.cost.replayed, 0);
  run.errors = { count: errorCount, sample: errors };
  const configIdentity = await options.configIdentityFor({ model: embedder.model, dims: header.generated.embedder.dims });
  const configIdentities = runEnvelope([configIdentity], configurations.map((row) => ({ rowId: row.key, identityId: configIdentity.identityId })));
  return { ...header, configIdentities, runs: [run], configurations };
}

/** What the long-horizon row needs from the run around it. */
interface HorizonContext {
  env: AiEnv;
  horizon: HorizonOptions;
  /** The run's thinking control — what the sub-calls are sent. */
  thinking: 'off' | 'default';
  questions: readonly QaQuestion[];
  perConversation: ReadonlyMap<string, Conversation>;
  samples: readonly LocomoSample[];
  shared: Account;
  timer: () => number;
  client: ChatClient;
  noteError: (message: string) => void;
  progress: (message: string) => void;
}

/**
 * The suite's own answer to a corpus that will not fit, over the
 * conversation as an environment: one fresh in-memory environment per
 * question holding the transcript in a `corpus` slot, the agent
 * authoring a program over its digest and fanning sub-calls over the
 * pieces it chunks, under a per-question turn budget and the run's
 * shared ceiling. Questions run one at a time — the fan-out inside a
 * question is the concurrency — and the row's ceiling is read from the
 * sub-call requests themselves: a gold turn some sub-call was shown.
 */
async function runHorizonRow(row: QaRow, ctx: HorizonContext): Promise<LiveConfiguration> {
  const { horizon, shared } = ctx;
  const f1 = f1Means();
  const ceiling = recallMeans();
  const citedRecall = recallMeans();
  const citations = { cited: 0, uncited: 0, total: 0, unresolved: 0, answersWithUnresolved: 0 };
  const unanswered = { wire: 0, budget: 0 };
  let invalid = 0;
  const cost = emptyCost();
  const latencies: number[] = [];
  const results: QuestionResult[] = [];
  const block: HorizonBlock = {
    perCategory: horizon.perCategory,
    depth: horizon.depth,
    turnsPerQuestion: horizon.turnsPerQuestion,
    maxSubcalls: horizon.maxSubcalls,
    callTimeoutMs: horizon.callTimeoutMs,
    thinking: { author: horizon.authorThinking, subcall: ctx.thinking },
    ids: ctx.questions.map((q) => q.id),
    authored: { ok: 0, failed: 0, attempts: 0 },
    programs: { ok: 0, failed: 0 },
    subcalls: { made: 0, failed: 0, unvisited: 0 },
    stops: {},
  };

  for (const s of ctx.samples) {
    const own = ctx.questions.filter((q) => q.sampleId === s.sample_id);
    if (own.length === 0) continue;
    const entry = ctx.perConversation.get(s.sample_id)!;
    const text = horizonCorpusText(entry.corpus);
    const listed = new Set(transcriptUnits(entry.corpus).map((u) => u.id));
    const prefix = `${s.sample_id}/`;

    for (const q of own) {
      if (shared.account.stop() !== null) { unanswered.budget++; continue; }
      const mine = emptyCost();
      let seen = '';
      const client = horizonClient(ctx.client, shared, [cost, mine], latencies, {
        onSubcall: (t) => { seen += `\n${t}`; },
        onFailure: (message) => ctx.noteError(`${q.id} ${message}`),
        timeoutMs: horizon.callTimeoutMs,
        authorThinkingOff: horizon.authorThinking === 'off',
        subcallThinkingOff: ctx.thinking === 'off',
      });
      const environment = createEnvironment({ compileQuery: compileJsonQuery });
      await environment.put('corpus', text, { kind: 'text', count: entry.corpus.turns.length });
      const agent = createLongHorizonAgent({
        client,
        environment,
        compileQuery: compileJsonQuery,
        createStructuredOutput,
        createProgramAuthor,
        createProgramRunner,
        createEnvironment,
        querySchema: QUERY_SCHEMA,
        depth: horizon.depth,
        maxSubcalls: horizon.maxSubcalls,
        maxConcurrentSubcalls: ctx.env.maxConcurrency,
        budget: { turns: horizon.turnsPerQuestion },
        clock: ctx.timer,
      });

      let result: any;
      try {
        result = await agent.run(horizonQuestion(q.text));
      } catch (error) {
        if (error instanceof BudgetStop) unanswered.budget++;
        else { unanswered.wire++; ctx.noteError(`${q.id}: ${error instanceof Error ? error.message : String(error)}`); }
        continue;
      }

      let authoredOk = false;
      let subcalls = 0;
      let failed = 0;
      let unvisited = 0;
      for (const step of result.trajectory ?? []) {
        if (step.kind === 'author') {
          if (step.ok === true) { block.authored.ok++; block.authored.attempts += typeof step.attempts === 'number' ? step.attempts : 1; authoredOk = true; }
          else block.authored.failed++;
        }
        if (step.kind === 'program') {
          if (step.ok === true) block.programs.ok++; else block.programs.failed++;
          subcalls += typeof step.subcalls === 'number' ? step.subcalls : 0;
          failed += typeof step.failed === 'number' ? step.failed : 0;
          for (const s2 of step.steps ?? []) unvisited += typeof s2.skipped === 'number' ? s2.skipped : 0;
        }
      }
      block.subcalls.made += subcalls;
      block.subcalls.failed += failed;
      block.subcalls.unvisited += unvisited;
      const stopped: string | null = typeof result.stopReason === 'string' ? result.stopReason : null;
      if (stopped !== null) block.stops[stopped] = (block.stops[stopped] ?? 0) + 1;

      const answerText = typeof result.answer?.text === 'string' ? result.answer.text : null;
      if (answerText === null) invalid++;
      const { answer, citations: cited } = answerText === null ? { answer: '', citations: [] } : horizonAnswer(answerText);
      const check = checkCitations(cited, listed);
      citations.total += cited.length;
      citations.unresolved += check.unresolved.length;
      if (check.unresolved.length > 0) citations.answersWithUnresolved++;
      if (check.resolved.length > 0) citations.cited++; else citations.uncited++;
      const reached = new Set(q.gold.filter((address) => address.startsWith(prefix) && seen.includes(`[${address.slice(prefix.length)}]`)));
      const citedAddresses = new Set(check.resolved.map((id) => addressOf(s.sample_id, id)));
      const own1 = f1Of(q, answer)!;
      const ceil = evidenceRecall(q.gold, reached);
      const citedR = evidenceRecall(q.gold, citedAddresses);
      f1.add(q.category, own1);
      ceiling.add(q.category, ceil);
      citedRecall.add(q.category, citedR);
      results.push({
        id: q.id, category: q.category as 1 | 2 | 3 | 4, f1: own1, ceiling: ceil, citedRecall: citedR,
        cited: check.resolved.length > 0, unresolved: check.unresolved.length, invalid: answerText === null, tokens: mine.tokens, ms: mine.ms, replayed: mine.replayed,
        calls: mine.turns, subcalls, failed, unvisited, authored: authoredOk, stopped,
      });
      ctx.progress(`${row.key} ${q.id}: ${mine.turns} calls, ${subcalls} sub-calls (${failed} failed, ${unvisited} pieces unvisited)${stopped === null ? '' : `, stopped: ${stopped}`}`);
    }
  }

  return {
    key: row.key,
    label: row.label,
    kind: row.kind,
    run: 0,
    questions: { planned: ctx.questions.length, answered: f1.size, unanswered, invalid, results },
    f1: f1.summary(),
    ceiling: ceiling.summary(),
    citedRecall: citedRecall.summary(),
    citations,
    cost,
    latency: latencyOf(latencies),
    adversarial: emptyAdversarial(),
    horizon: block,
  };
}

