/** Why two live reports cannot share a table, or `null` when they can. */
export function liveMismatch(existing: LiveReport, fresh: LiveReport): string | null {
  const a = existing.generated;
  const b = fresh.generated;
  if (existing.dataset.sha256 !== fresh.dataset.sha256) return `a different release (sha256 ${existing.dataset.sha256.slice(0, 12)}… against ${fresh.dataset.sha256.slice(0, 12)}…)`;
  if (a.provider !== b.provider || a.model !== b.model) return `a different answer model (\`${a.provider}\` \`${a.model}\` against \`${b.provider}\` \`${b.model}\`)`;
  if (a.judgeModel !== b.judgeModel) return `a different judge (\`${a.judgeModel}\` against \`${b.judgeModel}\`)`;
  if (a.thinking !== b.thinking) return `a different thinking control (${a.thinking} against ${b.thinking})`;
  if (a.embedder.model !== b.embedder.model) return `a different embedder (\`${a.embedder.model}\` against \`${b.embedder.model}\`)`;
  if (a.embedder.dims !== 0 && b.embedder.dims !== 0 && a.embedder.dims !== b.embedder.dims) return `a different embedding width (${a.embedder.dims} against ${b.embedder.dims})`;
  if (existing.config.k !== fresh.config.k) return `a different k (${existing.config.k} against ${fresh.config.k})`;
  if (JSON.stringify(existing.sample) !== JSON.stringify(fresh.sample)) return 'a different sample';
  if (JSON.stringify(existing.dataset.restricted) !== JSON.stringify(fresh.dataset.restricted)) return 'a different restriction of the release';
  return null;
}

/**
 * The committed live document is the merge of runs: a fresh run's rows
 * replace the rows of the same key and its run is appended, so one
 * table holds every row while every row still says which run — with
 * which plan and which spend — produced it. Two reports that would put
 * two models in one table are refused with the reason.
 */
export function mergeLiveReports(existing: LiveReport | null, fresh: LiveReport): LiveReport {
  if (existing === null) return { ...fresh, configurations: sortRows(fresh.configurations) };
  const mismatch = liveMismatch(existing, fresh);
  if (mismatch !== null) throw new Error(`the live reports cannot be merged: ${mismatch}; move the existing report aside to start a new table`);
  const offset = existing.runs.length;
  const freshRows = fresh.configurations.map((row) => ({ ...row, run: row.run + offset }));
  const replaced = new Set(freshRows.map((row) => row.key));
  const kept = existing.configurations.filter((row) => !replaced.has(row.key));
  const embedder = fresh.generated.embedder.dims === 0 ? existing.generated.embedder : fresh.generated.embedder;

  // the envelope merges by the same rule the rows do: a replaced row's
  // reference is the fresh one, a kept row keeps its recorded state, and
  // the identity table holds exactly the identities still referenced
  const keptRefs = existing.configIdentities.rows.filter((row) => !replaced.has(row.rowId));
  const rows = [...keptRefs, ...fresh.configIdentities.rows];
  const referenced = new Set(rows.flatMap((row) => (row.identityStatus === 'run' ? [row.identityId] : [])));
  const identities = [...existing.configIdentities.identities, ...fresh.configIdentities.identities]
    .filter((identity, index, all) => referenced.has(identity.identityId)
      && all.findIndex((other) => other.identityId === identity.identityId) === index);

  return {
    ...existing,
    generated: { ...fresh.generated, embedder },
    config: { ...fresh.config, embedder },
    configIdentities: { identities, rows },
    runs: [...existing.runs, ...fresh.runs],
    configurations: sortRows([...kept, ...freshRows]),
  };
}

function sortRows<T extends { key: string }>(rows: readonly T[]): T[] {
  const order = new Map(ROWS.map((row, i) => [row.key, i]));
  return [...rows].sort((a, b) => (order.get(a.key) ?? ROWS.length) - (order.get(b.key) ?? ROWS.length));
}

