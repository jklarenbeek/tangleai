/**
 * The LoCoMo answer path — the answer instrument, and the baselines
 * in the same table.
 *
 * The recall instrument measures the ceiling: was the evidence in the k
 * memories a
 * question retrieved at all. This instrument measures the other half —
 * what a model does with what retrieval handed it — and it publishes
 * the two TOGETHER, per row, because either alone lets a later change
 * claim a win it did not earn (jarenjs's long-horizon instrument
 * learned this; the lesson is inherited). A large gap between ceiling
 * and F1 is a prompting problem; a small gap under a low ceiling is a
 * retrieval problem.
 *
 * **Two tiers, one sample.**
 *
 *  - The KEYLESS tier runs on every commit and is the committed,
 *    byte-reproducible report: the scorer's gate (the released answer
 *    as its own prediction must score exactly 1.000 in every category,
 *    or nothing prints), then per row the ingest census, the
 *    evidence-recall ceiling at the k the prompt uses, and a model-free
 *    floor — the retrieved context QUOTED as the answer. It also draws
 *    the seeded, stratified sample the live tier answers, and lists its
 *    question ids, so the two tiers agree on what was asked.
 *  - The LIVE tier (`--live`) puts a real chat model and a real
 *    embedding wire — both from the desktop's provider settings — over
 *    the same corpus and the same sample. It is never a test
 *    dependency: no key is a stated skip, a plan that would exceed
 *    `TANGLE_AI_MAX_CALLS` is skipped up front with that reason rather
 *    than half-spent, and the report it writes is a dated document,
 *    validated and rendered by the tests but never regenerated by them.
 *
 * **The rows.** A LoCoMo number means nothing alone, so the
 * table holds the rivals beside Tangle, over the identical corpus,
 * questions, scorer and answer prompt:
 *
 *  - `long-context` — the whole conversation in the request, the
 *    paper's own headline baseline and the honest upper bound on "just
 *    send everything";
 *  - `near-raw` — the pipeline with every policy inert, which IS
 *    retrieval over raw dialog turns (the paper's `dialog` RAG row);
 *  - `rag-observation` and `rag-summary` — the release's two derived
 *    corpora, which the paper retrieves over instead of the dialog,
 *    ingested as evidence-carrying memories through the same pipeline
 *    and ranked at the same k;
 *  - `long-horizon` — the suite's own answer to a corpus that will not
 *    fit: `createLongHorizonAgent` over `createEnvironment`, authoring
 *    a compile-gated program and fanning sub-calls over the pieces;
 *  - `near` — Tangle, the shipped policies.
 *
 * Six rows do not fit one 200-request ceiling, so a live run answers a
 * chosen subset (`--rows`) and the committed live document is the MERGE
 * of such runs: rows keyed by name, every run recorded with its plan
 * and its spend, and a run that would mix models refused. The
 * long-horizon row multiplies calls per question by construction, so
 * it answers a seeded subset of the sample under a per-question turn
 * budget, and every other row is re-scored over that subset beside it.
 * Per-question results travel in the document, which is what lets the
 * rows be compared on the questions they ALL answered rather than on
 * overlapping sets.
 *
 * **The prompt is grounded and the citations are checkable.** The
 * model answers through `createStructuredOutput` with `{ answer,
 * citations }`; every citation must be an id the prompt listed, and
 * one that is not is a counted failure — the evidence rule reaches the
 * benchmark, not just the store. Beside F1 the row reports the recall
 * of the gold turns over the memories the model CITED, which is the
 * grounding number: did it use the right turns, not merely have them.
 * The long-horizon agent answers from a slot rather than a schema, so
 * its citations are the turn ids its answer text names.
 *
 * **What was bought once is not bought again.** Behind the wire cache
 * (`wire-cache.ts`, opened by the CLI), every corpus text already
 * embedded and every prompt already answered under the same model and
 * thinking control is remembered: the plan counts only the embedding
 * requests the cache cannot answer, and a chat call the cache remembers
 * comes back REPLAYED — counted in the row and in the run, charged to
 * no budget, its wall time the wall time of the call that bought it.
 * A row that lost answers to a rate limit is filled in by re-running
 * it for the price of the missing answers alone; `--fresh` buys
 * everything again; deleting `benchmark/cache/` starts over.
 *
 * **Cost sits in the same table as quality**, through `@jarenjs/ai`'s
 * `createBudgetAccount` (turns / tokens / ms, the provider's `usage`
 * preferred over any estimate), and latency is p50/p95 of the chat
 * call. Category 5 gets its own LLM-judge lane — the question's
 * premise is false by construction, and the judge asks whether the
 * answer refused it — reported separately and never folded into the
 * parity number.
 *
 * The prompts are Tangle's, not ported: `task_eval/` shows how the
 * official runners ask ("a short phrase … exact words from the context
 * whenever possible") and that instruction is kept, because the scorer
 * rewards it; the structure around it is this repository's.
 */

