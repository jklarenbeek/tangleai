/** Deterministic source qualification, denominator and comparison registration. */
import { censusLongMemEval, type LmeRawQuestion } from './longmemeval.ts';
import { LONGMEMEVAL_SOURCE, LONGMEMEVAL_FILES } from './longmemeval-source.ts';
import { registerTemporal } from './temporal-registration.ts';
import { canonicalizeJson } from '@jarenjs/json/canonical';
import { sha256 } from './longmemeval-source.ts';
import { createReportValidator } from './validate.ts';
import SCHEMA from '../schemas/longmemeval-report.schema.json' with { type: 'json' };

const validateShape = createReportValidator(SCHEMA);
export function validateLongMemEvalReport(value: unknown): boolean {
  if (!validateShape(value).valid) return false;
  const report = value as LongMemEvalReport;
  const { sha256: identity, ...registration } = report.registration;
  return sha256(canonicalizeJson(registration)) === identity &&
    canonicalizeJson(report.source) === canonicalizeJson(LONGMEMEVAL_SOURCE) &&
    canonicalizeJson(report.files) === canonicalizeJson(LONGMEMEVAL_FILES);
}

export function longMemEvalReport(rows: LmeRawQuestion[], locomoIds: string[]) {
  const census = censusLongMemEval(rows);
  const report = { status: 'measured' as const, instrument: 'longmemeval-census-v1', source: LONGMEMEVAL_SOURCE,
    files: LONGMEMEVAL_FILES, census, registration: registerTemporal(rows, locomoIds),
    denominators: { qa: census.questions, retrieval: census.questions - census.abstentions,
      profiles: [
        { name: 'provided-history', questions: census.questions, sessions: census.sessions, inaccessibleGoldSessions: 0, inaccessibleGoldQuestions: 0 },
        { name: 'strict-as-of', questions: census.questions, sessions: census.sessions - census.futureSessions,
          inaccessibleGoldSessions: census.futureGoldSessions, inaccessibleGoldQuestions: census.futureGoldQuestions },
      ] },
    discrepancies: [{ sourceQuestionId: '370a8ff4', kind: 'reported-reference-disagreement',
      strictDays: 81, strictWholeWeeks: 11, strictRemainingDays: 4, upstreamWeeks: 15, disposition: 'preserve-upstream-label' }],
  };
  if (!validateLongMemEvalReport(report)) throw new Error('LongMemEval report failed its denominator or identity contract');
  return report;
}
